CREATE TABLE PRODUCT (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(150) NOT NULL,
    VALIDITY_DATE TIMESTAMP(6),
    WAREHOUSE_ID NUMBER,
    COST_PRICE NUMBER(19,2),
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_DATE TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    MODIFY_DATE TIMESTAMP(6),

    CONSTRAINT FK_PRODUCT_WAREHOUSE
        FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSE(ID)
        ON DELETE SET NULL,

    CONSTRAINT CK_PRODUCT_STATUS
        CHECK (STATUS IN ('AVAILABLE','USED','DAMAGED','EXPIRED','DISCARDED')),

    CONSTRAINT CK_PRODUCT_COSTPRICE_NONNEG
        CHECK (COST_PRICE IS NULL OR COST_PRICE >= 0)
);

CREATE INDEX IDX_PRODUCT_WAREHOUSE_ID ON PRODUCT (WAREHOUSE_ID);
CREATE INDEX IDX_PRODUCT_VALIDITY_DATE ON PRODUCT (VALIDITY_DATE);
CREATE INDEX IDX_PRODUCT_STATUS ON PRODUCT (STATUS);

CREATE OR REPLACE TRIGGER TRG_PRODUCT_BIU
BEFORE INSERT OR UPDATE ON PRODUCT
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.CREATED_DATE IS NULL THEN
            :NEW.CREATED_DATE := SYSTIMESTAMP;
        END IF;
        :NEW.MODIFY_DATE := SYSTIMESTAMP;
    ELSIF UPDATING THEN
        :NEW.MODIFY_DATE := SYSTIMESTAMP;
    END IF;
END;