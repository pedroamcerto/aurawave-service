-- ============================================================================
-- TABELAS PRINCIPAIS (sem dependências)
-- ============================================================================

-- Tabela: SUPPLIER (Fornecedor)
CREATE TABLE SUPPLIER (
    ID NUMBER(19) NOT NULL,
    NM_SUPPLIER VARCHAR2(100 CHAR) NOT NULL,
    CPF VARCHAR2(11 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SUPPLIER PRIMARY KEY (ID),
    CONSTRAINT UK_SUPPLIER_CPF UNIQUE (CPF),
    CONSTRAINT CK_SUPPLIER_CPF CHECK (LENGTH(CPF) = 11)
);

-- Tabela: MANUFACTURER (Fabricante)
CREATE TABLE MANUFACTURER (
    ID NUMBER(19) NOT NULL,
    NM_MANUFACTURER VARCHAR2(100 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MANUFACTURER PRIMARY KEY (ID)
);

-- Tabela: LABORATORY (Laboratório)
CREATE TABLE LABORATORY (
    ID NUMBER(19) NOT NULL,
    NM_LABORATORY VARCHAR2(65 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_LABORATORY PRIMARY KEY (ID)
);

-- Tabela: COLLABORATOR (Colaborador)
CREATE TABLE COLLABORATOR (
    ID NUMBER(19) NOT NULL,
    NM_COLLABORATOR VARCHAR2(300 CHAR) NOT NULL,
    COD_COMPANY VARCHAR2(350 CHAR) NOT NULL,
    CPF VARCHAR2(11 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_COLLABORATOR PRIMARY KEY (ID),
    CONSTRAINT UK_COLLABORATOR_CPF UNIQUE (CPF),
    CONSTRAINT CK_COLLABORATOR_CPF CHECK (LENGTH(CPF) = 11)
);

-- ============================================================================
-- TABELAS COM DEPENDÊNCIAS DE 1º NÍVEL
-- ============================================================================

-- Tabela: BATCH (Lote) - depende de SUPPLIER
CREATE TABLE BATCH (
    ID NUMBER(19) NOT NULL,
    NM_BATCH VARCHAR2(200 CHAR) NOT NULL,
    SUPPLIER_ID_SUPPLIER NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_BATCH PRIMARY KEY (ID),
    CONSTRAINT FK_BATCH_SUPPLIER FOREIGN KEY (SUPPLIER_ID_SUPPLIER) 
        REFERENCES SUPPLIER(ID) ON DELETE CASCADE
);

-- Tabela: MODEL (Modelo) - depende de MANUFACTURER
CREATE TABLE MODEL (
    ID NUMBER(19) NOT NULL,
    NM_MODEL VARCHAR2(60 CHAR) NOT NULL,
    MANUFACTURER_ID_MANUFACTURER NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MODEL PRIMARY KEY (ID),
    CONSTRAINT FK_MODEL_MANUFACTURER FOREIGN KEY (MANUFACTURER_ID_MANUFACTURER) 
        REFERENCES MANUFACTURER(ID) ON DELETE CASCADE
);

-- Tabela: WAREHOUSE (Almoxarifado) - depende de LABORATORY
CREATE TABLE WAREHOUSE (
    ID NUMBER(19) NOT NULL,
    NM_WAREHOUSE VARCHAR2(80 CHAR) NOT NULL,
    LABORATORY_ID_LABORATORY NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_WAREHOUSE PRIMARY KEY (ID),
    CONSTRAINT FK_WAREHOUSE_LABORATORY FOREIGN KEY (LABORATORY_ID_LABORATORY) 
        REFERENCES LABORATORY(ID) ON DELETE CASCADE
);

-- ============================================================================
-- TABELAS COM DEPENDÊNCIAS DE 2º NÍVEL
-- ============================================================================

-- Tabela: PRODUCT (Produto) - depende de WAREHOUSE
CREATE TABLE PRODUCT (
    ID NUMBER(19) NOT NULL,
    NAME VARCHAR2(100 CHAR) NOT NULL,
    VALIDITY_DATE TIMESTAMP,
    WAREHOUSE_ID NUMBER(19) NOT NULL,
    COST_PRICE NUMBER(10,2) NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_PRODUCT PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUCT_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID) 
        REFERENCES WAREHOUSE(ID) ON DELETE CASCADE,
    CONSTRAINT CK_PRODUCT_STATUS CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'EXPIRED')),
    CONSTRAINT CK_PRODUCT_PRICE CHECK (COST_PRICE >= 0)
);

-- Tabela: ITEM - depende de MODEL e BATCH
CREATE TABLE ITEM (
    ID NUMBER(19) NOT NULL,
    NM_ITEM VARCHAR2(100 CHAR) NOT NULL,
    STATUS VARCHAR2(60 CHAR) NOT NULL,
    MODEL_ID_MODEL NUMBER(19) NOT NULL,
    BATCH_ID_BATCH NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_ITEM_MODEL FOREIGN KEY (MODEL_ID_MODEL) 
        REFERENCES MODEL(ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_BATCH FOREIGN KEY (BATCH_ID_BATCH) 
        REFERENCES BATCH(ID) ON DELETE CASCADE
);

-- Tabela: SESSION (Sessão) - depende de WAREHOUSE e COLLABORATOR
CREATE TABLE SESSION (
    ID NUMBER(19) NOT NULL,
    START TIMESTAMP NOT NULL,
    "END" TIMESTAMP NOT NULL,
    WAREHOUSE_ID_WAREHOUSE NUMBER(19) NOT NULL,
    COLLABORATOR_ID_COLLABORATOR NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SESSION PRIMARY KEY (ID),
    CONSTRAINT FK_SESSION_WAREHOUSE FOREIGN KEY (WAREHOUSE_ID_WAREHOUSE) 
        REFERENCES WAREHOUSE(ID) ON DELETE CASCADE,
    CONSTRAINT FK_SESSION_COLLABORATOR FOREIGN KEY (COLLABORATOR_ID_COLLABORATOR) 
        REFERENCES COLLABORATOR(ID) ON DELETE CASCADE,
    CONSTRAINT CK_SESSION_DATES CHECK ("END" > START)
);

-- ============================================================================
-- TABELAS COM DEPENDÊNCIAS DE 3º NÍVEL
-- ============================================================================

-- Tabela: EVENT (Evento) - depende de ITEM
CREATE TABLE EVENT (
    ID NUMBER(19) NOT NULL,
    EVENT_TYPE VARCHAR2(50 CHAR) NOT NULL,
    EVENT VARCHAR2(200 CHAR) NOT NULL,
    ITEM_ID_ITEM NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_EVENT PRIMARY KEY (ID),
    CONSTRAINT FK_EVENT_ITEM FOREIGN KEY (ITEM_ID_ITEM) 
        REFERENCES ITEM(ID) ON DELETE CASCADE
);

