    CONSTRAINT FK_BATCH_SUPPLIER_SUPPLIER FOREIGN KEY (SUPPLIER_ID) 
        REFERENCES SUPPLIER(ID) ON DELETE CASCADE
);

-- Relacionamento: ITEM <-> MODEL
CREATE TABLE ITEM_MODEL (
    ITEM_ID NUMBER(19) NOT NULL,
