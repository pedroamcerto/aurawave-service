    CONSTRAINT FK_MODEL_PRODUCT_PRODUCT FOREIGN KEY (PRODUCT_ID) 
        REFERENCES PRODUCT(ID) ON DELETE CASCADE
);

-- Relacionamento: SESSION <-> COLLABORATOR
CREATE TABLE SESSION_COLLABORATOR (
    SESSION_ID NUMBER(19) NOT NULL,
    COLLABORATOR_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_SESSION_COLLABORATOR PRIMARY KEY (SESSION_ID, COLLABORATOR_ID),
    CONSTRAINT FK_SESSION_COLLABORATOR_SESSION FOREIGN KEY (SESSION_ID) 
        REFERENCES SESSION(ID) ON DELETE CASCADE,
    CONSTRAINT FK_SESSION_COLLABORATOR_COLLABORATOR FOREIGN KEY (COLLABORATOR_ID) 
