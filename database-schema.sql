        REFERENCES ITEM(ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_MODEL_MODEL FOREIGN KEY (MODEL_ID) 
        REFERENCES MODEL(ID) ON DELETE CASCADE
);

-- Relacionamento: ITEM <-> BATCH
CREATE TABLE ITEM_BATCH (
    ITEM_ID NUMBER(19) NOT NULL,
    BATCH_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ITEM_BATCH PRIMARY KEY (ITEM_ID, BATCH_ID),
    CONSTRAINT FK_ITEM_BATCH_ITEM FOREIGN KEY (ITEM_ID) 
        REFERENCES ITEM(ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_BATCH_BATCH FOREIGN KEY (BATCH_ID) 
        REFERENCES BATCH(ID) ON DELETE CASCADE
);

-- Relacionamento: MODEL <-> MANUFACTURER
CREATE TABLE MODEL_MANUFACTURER (
    MODEL_ID NUMBER(19) NOT NULL,
    MANUFACTURER_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MODEL_MANUFACTURER PRIMARY KEY (MODEL_ID, MANUFACTURER_ID),
    CONSTRAINT FK_MODEL_MANUFACTURER_MODEL FOREIGN KEY (MODEL_ID) 
        REFERENCES MODEL(ID) ON DELETE CASCADE,
    CONSTRAINT FK_MODEL_MANUFACTURER_MANUFACTURER FOREIGN KEY (MANUFACTURER_ID) 
        REFERENCES MANUFACTURER(ID) ON DELETE CASCADE
);

-- Relacionamento: MODEL <-> PRODUCT
CREATE TABLE MODEL_PRODUCT (
    MODEL_ID NUMBER(19) NOT NULL,
    PRODUCT_ID NUMBER(19) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_MODEL_PRODUCT PRIMARY KEY (MODEL_ID, PRODUCT_ID),
    CONSTRAINT FK_MODEL_PRODUCT_MODEL FOREIGN KEY (MODEL_ID) 
